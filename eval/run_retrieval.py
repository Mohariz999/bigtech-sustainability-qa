"""Score retrieval on the eval questions. No LLM involved.

For every answerable question, a search "hits" when a returned chunk comes
from one of the question's cited (doc_id, page) pairs.

- hit@1 / hit@5: right page ranked first / anywhere in the top 5
- MRR: mean of 1/rank of the first correct chunk (0 if not in the top 10)

Each method is run three ways: no filter, a company filter, and a company +
data-year filter, both parsed from the question text (search.company_in, year_in). Results go to
eval/results/retrieval.md, and every miss to eval/results/retrieval_misses.jsonl.

Run: python eval/run_retrieval.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from search import Searcher, company_in, year_in  # noqa: E402

K = 10
OUT = ROOT / "eval" / "results"


def gold_pages(q: dict) -> set[tuple[str, int]]:
    return {(s["doc_id"], p) for s in q["sources"] for p in s["pages"]}


def evidence_survived_ingest(searcher: Searcher, q: dict) -> bool:
    """Is the evidence quote still inside some chunk on a cited page? (Boilerplate removal could cut it.)"""
    probe = q["evidence"].replace("’", "'")[:60]
    for doc_id, page in gold_pages(q):
        rows = searcher.db.execute("SELECT text FROM chunks WHERE doc_id=? AND page=?", (doc_id, page)).fetchall()
        if any(probe in r[0] for r in rows):
            return True
    return False


def main() -> None:
    questions = [json.loads(l) for l in open(ROOT / "eval" / "questions.jsonl") if l.strip()]
    answerable = [q for q in questions if not q["category"].startswith("not_found")]
    s = Searcher()

    lost = [q["id"] for q in answerable if not evidence_survived_ingest(s, q)]
    print(f"Evidence lost during ingest: {lost or 'none'}")

    results, misses = [], []
    for method in ("keyword", "vector", "hybrid"):
        for flt in ("none", "company", "company+year"):
            h1 = h5 = rr = 0.0
            for q in answerable:
                company = company_in(q["question"]) if flt != "none" else None
                year = year_in(q["question"]) if flt == "company+year" else None
                hits = getattr(s, method)(q["question"], K, company=company, data_year=year)
                gold = gold_pages(q)
                rank = next((i + 1 for i, h in enumerate(hits) if (h.doc_id, h.page) in gold), None)
                h1 += rank == 1
                h5 += rank is not None and rank <= 5
                rr += 1 / rank if rank else 0
                if method == "hybrid" and flt == "company+year" and not (rank and rank <= 5):
                    misses.append({"id": q["id"], "category": q["category"], "question": q["question"],
                                   "gold": sorted(gold), "rank": rank,
                                   "top5": [f"{h.doc_id} p{h.page}" for h in hits[:5]]})
            n = len(answerable)
            results.append((method, flt, h1 / n, h5 / n, rr / n))
            print(f"{method:8} filter={flt:13} hit@1={h1/n:.0%} hit@5={h5/n:.0%} MRR={rr/n:.2f}")

    # Not-found questions: does the top vector score look different from answerable ones?
    top_scores = {q["id"]: s.vector(q["question"], 1, company=company_in(q["question"]), data_year=year_in(q["question"]))[0].score for q in questions}
    ans = sorted(top_scores[q["id"]] for q in answerable)
    nf = {q["id"]: top_scores[q["id"]] for q in questions if q["category"].startswith("not_found")}

    OUT.mkdir(exist_ok=True)
    with open(OUT / "retrieval.md", "w") as f:
        f.write(f"# Retrieval results\n\n{len(answerable)} answerable questions, top {K} retrieved. "
                "Generated by `eval/run_retrieval.py`.\n\n")
        f.write("| Method | Filter | hit@1 | hit@5 | MRR |\n|---|---|---|---|---|\n")
        for m, flt, a, b, c in results:
            f.write(f"| {m} | {flt} | {a:.0%} | {b:.0%} | {c:.2f} |\n")
        f.write(f"\nEvidence lost during ingest: {', '.join(lost) or 'none'}\n")
        f.write("\n## Top vector similarity: answerable vs not-found\n\n")
        f.write(f"Answerable questions: min {ans[0]:.3f}, median {ans[len(ans)//2]:.3f}, max {ans[-1]:.3f}\n\n")
        for qid, sc in nf.items():
            f.write(f"- {qid} (not found): {sc:.3f}\n")
        f.write(f"\n## Hybrid + company+year filter: misses at top 5 ({len(misses)})\n\n")
        for m in misses:
            f.write(f"- **{m['id']}** [{m['category']}] {m['question']}  \n  wanted {m['gold']}, "
                    f"rank={m['rank']}, got {m['top5']}\n")
    with open(OUT / "retrieval_misses.jsonl", "w") as f:
        f.writelines(json.dumps(m) + "\n" for m in misses)
    print(f"\nanswerable top-1 similarity: min {ans[0]:.3f} median {ans[len(ans)//2]:.3f}")
    print("not-found top-1 similarity:", {k: round(v, 3) for k, v in nf.items()})
    print(f"Wrote {(OUT / 'retrieval.md').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
