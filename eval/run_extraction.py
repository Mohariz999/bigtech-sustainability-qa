"""Score the `facts` table against hand-checked gold facts (eval/facts_gold.jsonl). No API calls.

For each gold fact, look up extracted facts with the same company, metric and year:
- correct:  one of them has an accepted value (within 0.5%)
- wrong:    some were extracted, but none has an accepted value
- missing:  none extracted (also says whether the gold page was even a candidate page)

Also lists conflicts: the same company + metric + year extracted with different values.
Some conflicts are real (Microsoft publishes two emissions totals), others are errors.

Run: python eval/run_extraction.py
"""
import collections
import json
import pathlib
import re
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from extract import DB_PATH, candidate_pages, normalise  # noqa: E402
from fact_quality import normalize_unit  # noqa: E402
from diagnostics import create_run  # noqa: E402

OUT = ROOT / "eval" / "results" / "extraction.md"


def year_of(period: str) -> int | None:
    """'2025', 'FY25', 'FY2025', 'fiscal year 2025' -> 2025."""
    if m := re.search(r"\b(20\d\d)\b", period):
        return int(m.group(1))
    if m := re.search(r"FY\s?(\d\d)\b", period, re.I):
        return 2000 + int(m.group(1))
    return None


def close(a: float, b: float) -> bool:
    return abs(a - b) <= 0.005 * max(abs(a), abs(b), 1e-9)


def unit_aware_match(gold: dict, found: list[dict]) -> bool | None:
    """No unit in legacy gold means unknown, not an inferred unit-aware success.

    This verifies numeric/unit compatibility only, not scope, basis or attribution.
    """
    if not gold.get("unit"):
        return None
    targets = [normalize_unit(value, gold["unit"]) for value in gold["values"]]
    targets = [target for target in targets if target["dimension"] != "unknown"]
    if not targets:
        return None
    for fact in found:
        actual = normalize_unit(fact["value"], fact["unit"])
        if any(actual["dimension"] == target["dimension"] and close(actual["value"], target["value"])
               for target in targets):
            return True
    return False


def main() -> None:
    global OUT
    db = sqlite3.connect(DB_PATH)
    gold = [json.loads(l) for l in open(ROOT / "eval" / "facts_gold.jsonl") if l.strip()]
    pages = {(p["doc_id"], p["page"]): p["text"] for p in candidate_pages(db)}
    page_text = {}
    for doc_id, page, text in db.execute("SELECT doc_id, page, text FROM chunks"):
        page_text[(doc_id, page)] = page_text.get((doc_id, page), "") + " " + text

    facts = [dict(zip(("company", "doc_id", "page", "metric", "value", "unit", "period", "basis", "quote"), r))
             for r in db.execute("SELECT company, doc_id, page, metric, value, unit, period, basis, quote FROM facts")]
    index = collections.defaultdict(list)
    for f in facts:
        index[(f["company"], f["metric"], year_of(f["period"]))].append(f)

    results = collections.Counter()
    lines = []
    for g in gold:
        assert normalise(g["evidence"]) in normalise(page_text[(g["doc_id"], g["page"])]), f"{g['id']}: bad evidence"
        found = index[(g["company"], g["metric"], g["year"])]
        if any(close(f["value"], v) for f in found for v in g["values"]):
            outcome = "correct"
        elif found:
            outcome = "wrong"
        else:
            outcome = "missing"
        results[outcome] += 1
        got = ", ".join(f"{f['value']:g} {f['unit']} ({f['doc_id']} p{f['page']})" for f in found[:4]) or "-"
        candidate = "" if (g["doc_id"], g["page"]) in pages else " (gold page was not a candidate page)"
        lines.append(f"| {g['id']} | {g['company']} | {g['metric']} | {g['year']} | "
                     f"{' or '.join(f'{v:g}' for v in g['values'])} | {outcome}{candidate} | {got} | "
                     f"{unit_aware_match(g, found) if g.get('unit') else 'unverified: gold has no unit'} |")

    conflicts = []
    for (company, metric, year), fs in sorted(index.items(), key=lambda x: str(x[0])):
        values = sorted({round(f["value"], 6) for f in fs})
        if year and len(values) > 1:
            conflicts.append(f"- {company} {metric} {year}: " + ", ".join(
                f"{v:g} ({', '.join(sorted({f['basis'] or 'no basis' for f in fs if round(f['value'], 6) == v}))})"
                for v in values))

    n = len(gold)
    by_company = collections.Counter(f["company"] for f in facts)
    by_metric = collections.Counter(f["metric"] for f in facts)
    run_dir = create_run(ROOT, ROOT / "eval/facts_gold.jsonl",
                         {"system": "extraction", "grading": "legacy-numeric-plus-explicit-unit-check",
                          "result_kind": "offline_extraction_audit"})
    OUT = run_dir / "extraction.md"
    with open(OUT, "x") as out:
        out.write("# Extraction results\n\nGenerated by `eval/run_extraction.py` from the `facts` table.\n\n")
        out.write(f"**{results['correct']}/{n} legacy raw-number matches**, {results['wrong']} wrong, {results['missing']} missing.\n\n")
        out.write("Unit-aware numeric validation is reported separately; missing gold units cannot be inferred. "
                  "Neither raw-number matching nor unit conversion verifies scope, basis or attribution.\n\n")
        out.write(f"Facts in the table: {len(facts)}. By company: {dict(by_company.most_common())}. "
                  f"By metric: {dict(by_metric.most_common())}.\n\n")
        out.write("| Gold | Company | Metric | Year | Expected | Legacy outcome | Extracted (first 4) | Unit-aware numeric match |\n|---|---|---|---|---|---|---|---|\n")
        out.write("\n".join(lines) + "\n")
        out.write(f"\n## Conflicts: same company, metric and year, different values ({len(conflicts)})\n\n")
        out.write("\n".join(conflicts) + "\n")
    print(f"{results['correct']}/{n} legacy raw-number matches, {results['wrong']} wrong, {results['missing']} missing. "
          f"{len(facts)} facts, {len(conflicts)} conflicts. Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
